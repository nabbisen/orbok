/// Supported UI locales. Default English; persisted in the catalog
/// under the `ui.locale` setting (read/written by `orbok`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Locale {
    #[default]
    En,
    Ja,
}

impl Locale {
    pub const ALL: &'static [Locale] = &[Locale::En, Locale::Ja];

    /// Setting string stored in `app_settings` (`"en"` / `"ja"`).
    pub fn as_str(&self) -> &'static str {
        match self {
            Locale::En => "en",
            Locale::Ja => "ja",
        }
    }

    pub fn parse(s: &str) -> Option<Locale> {
        match s {
            "en" => Some(Locale::En),
            "ja" => Some(Locale::Ja),
            _ => None,
        }
    }

    /// Detect the preferred locale from the operating system environment.
    /// Checks `LANG` and `LANGUAGE` in that order. Returns `None` if
    /// neither variable is set or contains a recognised language code.
    /// Japanese is recognised when the value starts with `ja` (e.g. `ja`,
    /// `ja_JP`, `ja_JP.UTF-8`).
    pub fn from_env() -> Option<Locale> {
        for var in &["LANG", "LANGUAGE"] {
            if let Ok(val) = std::env::var(var)
                && let Some(locale) = Self::parse_env_value(&val)
            {
                return Some(locale);
            }
        }
        None
    }

    #[cfg(test)]
    pub(crate) fn from_env_values(lang: Option<&str>, language: Option<&str>) -> Option<Locale> {
        [lang, language]
            .into_iter()
            .flatten()
            .find_map(Self::parse_env_value)
    }

    fn parse_env_value(value: &str) -> Option<Locale> {
        let lower = value.to_lowercase();
        if lower.starts_with("ja") {
            Some(Locale::Ja)
        } else if lower.starts_with("en") {
            Some(Locale::En)
        } else {
            None
        }
    }

    /// Self-described language name, shown in the language picker.
    pub fn display_name(&self) -> &'static str {
        match self {
            Locale::En => "English",
            Locale::Ja => "日本語",
        }
    }
}

/// Defines [`MessageKey`] and generates `ALL_KEYS` from the exact same
/// variant list, so a new key cannot exist without appearing in the
/// exhaustiveness-test coverage (Review 134 §4, Review 138 §3(a)).
/// Previously `ALL_KEYS` was a hand-maintained `pub const` next to the
/// enum in `tests.rs` and had silently drifted to cover 257 of 273
/// variants before this fix -- deriving both from one list makes that
/// drift impossible rather than merely caught by review.
macro_rules! message_keys {
    ($(
        $(#[$variant_meta:meta])*
        $variant:ident
    ),+ $(,)?) => {
        /// Every fixed UI string. One variant per string; views never embed
        /// literals (RFC-031 §6 rule 1).
        #[derive(Debug, Clone, Copy, PartialEq, Eq)]
        pub enum MessageKey {
            $(
                $(#[$variant_meta])*
                $variant,
            )+
        }

        /// Every `MessageKey` variant, generated by [`message_keys`] from
        /// the same list that defines the enum.
        pub const ALL_KEYS: &[MessageKey] = &[
            $(MessageKey::$variant),+
        ];
    };
}

