/// Parameterized current/total file position with completed-state clamping.
pub fn model_file_position(locale: Locale, files_done: u32, files_total: u32) -> String {
    if files_total == 0 {
        return match locale {
            Locale::En => "Preparing files".to_string(),
            Locale::Ja => "ファイルを準備中".to_string(),
        };
    }
    let current = files_done.saturating_add(1).min(files_total);
    match locale {
        Locale::En => format!("File {current} of {files_total}"),
        Locale::Ja => format!("ファイル {current}/{files_total}"),
    }
}

/// Parameterized byte progress with localized byte units and percentage.
pub fn model_transfer_progress(locale: Locale, bytes: u64, total: u64) -> String {
    let exact_bytes = bytes;
    let bytes = model_bytes(locale, exact_bytes);
    if total == 0 {
        return bytes;
    }
    let transferred = model_bytes(locale, total);
    let ratio = (exact_bytes as f64 / total as f64).clamp(0.0, 1.0);
    format!("{bytes} / {transferred} ({:.0}%)", ratio * 100.0)
}

fn model_bytes(locale: Locale, bytes: u64) -> String {
    if bytes >= 1_000_000 {
        format!("{:.1} MB", bytes as f64 / 1_000_000.0)
    } else if bytes >= 1_000 {
        format!("{:.0} KB", bytes as f64 / 1_000.0)
    } else {
        match locale {
            Locale::En => format!("{bytes} B"),
            Locale::Ja => format!("{bytes} バイト"),
        }
    }
}

/// Parameterized: source card summary line. Built from the Preparing page's
/// own labels (`FileCountState::label_key`), label then number -- one word
/// per state, in one place, for both screens (Task 104). "Ready" is always
/// shown; any other segment only when its count is non-zero, the rule the
/// Preparing page already follows outside Advanced view. (Task 080 added the
/// no-text segment under the same rule.)
pub fn source_summary(
    locale: Locale,
    indexed: u64,
    stale: u64,
    failed: u64,
    no_text_found: u64,
) -> String {
    [
        (FileCountState::Ready, indexed),
        (FileCountState::NeedsUpdate, stale),
        (FileCountState::Failed, failed),
        (FileCountState::NoText, no_text_found),
    ]
    .into_iter()
    .filter(|&(state, count)| state == FileCountState::Ready || count > 0)
    .map(|(state, count)| format!("{} {count}", tr(locale, state.label_key())))
    .collect::<Vec<_>>()
    .join(" · ")
}

